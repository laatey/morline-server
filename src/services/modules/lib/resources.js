// CRUD resource generator: the model describes a data model, this writes the routes, validation
// schemas and migration. Deterministic, so no tokens are spent on boilerplate and no SQL is
// ever built from model output at runtime (names are validated here, values are parameterised).

import { EngineError } from './util.js';

const NAME = /^[a-z][a-z0-9_]{0,29}$/;
const PG_FIELD = /^[a-z][a-z0-9_]{0,29}$/;
const MONGO_FIELD = /^[a-zA-Z][a-zA-Z0-9_]{0,29}$/;
const RESERVED_ROUTES = new Set(['auth', 'health', 'ready', 'docs', 'metrics', 'webhooks', 'index', 'root']);
const RESERVED_FIELDS = new Set(['id', '_id', 'created_at', 'updated_at', 'createdat', 'updatedat']);
export const FIELD_TYPES = ['string', 'text', 'integer', 'number', 'boolean', 'datetime'];

const PG_TYPE = { string: 'text', text: 'text', integer: 'integer', number: 'double precision', boolean: 'boolean', datetime: 'timestamptz' };
const SCHEMA = {
  string: { type: 'string', maxLength: 500 },
  text: { type: 'string', maxLength: 20000 },
  integer: { type: 'integer' },
  number: { type: 'number' },
  boolean: { type: 'boolean' },
  datetime: { type: 'string', format: 'date-time' }
};

export function validateResource(spec, db) {
  const bad = (m) => new EngineError(`Resource ${JSON.stringify(spec?.name)}: ${m}`, 'bad_resource');
  if (!spec || typeof spec !== 'object') throw new EngineError('Each resource must be an object', 'bad_resource');
  if (typeof spec.name !== 'string' || !NAME.test(spec.name)) throw bad('name must be lowercase letters, digits or underscores, starting with a letter (for example "orders")');
  if (RESERVED_ROUTES.has(spec.name)) throw bad('that name is reserved');
  if (!Array.isArray(spec.fields) || !spec.fields.length || spec.fields.length > 20) throw bad('needs 1 to 20 fields');
  const fieldName = db === 'postgres' ? PG_FIELD : MONGO_FIELD;
  const seen = new Set();
  const fields = spec.fields.map((f) => {
    if (!f || typeof f.name !== 'string' || !fieldName.test(f.name)) throw bad(`field names must match ${fieldName} for ${db}`);
    if (RESERVED_FIELDS.has(f.name.toLowerCase())) throw bad(`"${f.name}" is a reserved field name`);
    if (seen.has(f.name)) throw bad(`duplicate field "${f.name}"`);
    seen.add(f.name);
    if (!FIELD_TYPES.includes(f.type)) throw bad(`field "${f.name}" has type "${f.type}"; use ${FIELD_TYPES.join(', ')}`);
    return { name: f.name, type: f.type, required: f.required === true, unique: f.unique === true };
  });
  return { name: spec.name, fields };
}

const q = (s) => `"${s}"`;
const json = (v) => JSON.stringify(v, null, 2);

function properties(fields) {
  return Object.fromEntries(fields.map((f) => [f.name, SCHEMA[f.type]]));
}

export function migrationSql(res) {
  const cols = res.fields.map((f) => `  ${q(f.name)} ${PG_TYPE[f.type]}${f.required ? ' not null' : ''}${f.unique ? ' unique' : ''}`);
  return [
    `create table ${q(res.name)} (`,
    '  id uuid primary key default gen_random_uuid(),',
    ...cols.map((c) => `${c},`),
    '  created_at timestamptz not null default now(),',
    '  updated_at timestamptz not null default now()',
    ');',
    ''
  ].join('\n');
}

const head = (name) => `// Generated by Morline for the "${name}" resource. Edit freely: it is your code now.`;
const camel = (s) => s.replace(/_([a-z0-9])/g, (_m, c) => c.toUpperCase());

export function postgresRoutes(res) {
  const cols = res.fields.map((f) => q(f.name)).join(', ');
  const marks = res.fields.map((_f, i) => `$${i + 1}`).join(', ');
  const fn = `${camel(res.name)}Routes`;
  return [
    head(res.name),
    "import { notFound } from '../lib/errors.js';",
    '',
    `export const prefix = '/${res.name}';`,
    '',
    `const fields = ${json(properties(res.fields))};`,
    `const required = ${JSON.stringify(res.fields.filter((f) => f.required).map((f) => f.name))};`,
    'const columns = Object.keys(fields);',
    '',
    "const createBody = { type: 'object', additionalProperties: false, required, properties: fields };",
    "const updateBody = { type: 'object', additionalProperties: false, minProperties: 1, properties: fields };",
    "const params = { type: 'object', required: ['id'], properties: { id: { type: 'string', format: 'uuid' } } };",
    'const page = {',
    "  type: 'object',",
    '  properties: {',
    "    limit: { type: 'integer', minimum: 1, maximum: 100, default: 20 },",
    "    offset: { type: 'integer', minimum: 0, default: 0 }",
    '  }',
    '};',
    '',
    `export default async function ${fn}(app) {`,
    "  app.get('/', { schema: { querystring: page } }, async (req) => {",
    '    const { limit, offset } = req.query;',
    `    const { rows } = await app.pg.query('select * from ${q(res.name)} order by created_at desc, id limit $1 offset $2', [limit, offset]);`,
    '    return { items: rows, limit, offset };',
    '  });',
    '',
    "  app.get('/:id', { schema: { params } }, async (req) => {",
    `    const { rows } = await app.pg.query('select * from ${q(res.name)} where id = $1', [req.params.id]);`,
    `    if (!rows[0]) throw notFound('${res.name} item not found');`,
    '    return rows[0];',
    '  });',
    '',
    "  app.post('/', { schema: { body: createBody } }, async (req, reply) => {",
    '    const values = columns.map((column) => req.body[column] ?? null);',
    '    const { rows } = await app.pg.query(',
    `      'insert into ${q(res.name)} (${cols}) values (${marks}) returning *',`,
    '      values',
    '    );',
    '    return reply.status(201).send(rows[0]);',
    '  });',
    '',
    "  app.patch('/:id', { schema: { params, body: updateBody } }, async (req) => {",
    '    // The schema only admits declared columns, so building the SET clause from the keys is safe.',
    '    const keys = Object.keys(req.body);',
    '    const sets = keys.map((key, i) => `"${key}" = $${i + 2}`);',
    '    const { rows } = await app.pg.query(',
    `      \`update ${q(res.name)} set \${sets.join(', ')}, updated_at = now() where id = $1 returning *\`,`,
    '      [req.params.id, ...keys.map((key) => req.body[key])]',
    '    );',
    `    if (!rows[0]) throw notFound('${res.name} item not found');`,
    '    return rows[0];',
    '  });',
    '',
    "  app.delete('/:id', { schema: { params } }, async (req, reply) => {",
    `    const { rowCount } = await app.pg.query('delete from ${q(res.name)} where id = $1', [req.params.id]);`,
    `    if (!rowCount) throw notFound('${res.name} item not found');`,
    '    return reply.status(204).send();',
    '  });',
    '}',
    ''
  ].join('\n');
}

export function mongoRoutes(res) {
  const fn = `${camel(res.name)}Routes`;
  return [
    head(res.name),
    "import { ObjectId } from 'mongodb';",
    "import { notFound } from '../lib/errors.js';",
    '',
    `export const prefix = '/${res.name}';`,
    '',
    `const fields = ${json(properties(res.fields))};`,
    `const required = ${JSON.stringify(res.fields.filter((f) => f.required).map((f) => f.name))};`,
    '',
    "const createBody = { type: 'object', additionalProperties: false, required, properties: fields };",
    "const updateBody = { type: 'object', additionalProperties: false, minProperties: 1, properties: fields };",
    "const params = { type: 'object', required: ['id'], properties: { id: { type: 'string', pattern: '^[a-f0-9]{24}$' } } };",
    'const page = {',
    "  type: 'object',",
    '  properties: {',
    "    limit: { type: 'integer', minimum: 1, maximum: 100, default: 20 },",
    "    offset: { type: 'integer', minimum: 0, default: 0 }",
    '  }',
    '};',
    '',
    'const present = ({ _id, ...doc }) => ({ id: _id.toString(), ...doc });',
    '',
    `export default async function ${fn}(app) {`,
    `  const collection = app.mongo.db().collection('${res.name}');`,
    ...res.fields.filter((f) => f.unique).map((f) => `  await collection.createIndex({ ${JSON.stringify(f.name)}: 1 }, { unique: true });`),
    '',
    "  app.get('/', { schema: { querystring: page } }, async (req) => {",
    '    const { limit, offset } = req.query;',
    '    const items = await collection.find().sort({ createdAt: -1, _id: 1 }).skip(offset).limit(limit).toArray();',
    '    return { items: items.map(present), limit, offset };',
    '  });',
    '',
    "  app.get('/:id', { schema: { params } }, async (req) => {",
    '    const doc = await collection.findOne({ _id: new ObjectId(req.params.id) });',
    `    if (!doc) throw notFound('${res.name} item not found');`,
    '    return present(doc);',
    '  });',
    '',
    "  app.post('/', { schema: { body: createBody } }, async (req, reply) => {",
    '    const now = new Date();',
    '    const doc = { ...req.body, createdAt: now, updatedAt: now };',
    '    const { insertedId } = await collection.insertOne(doc);',
    '    return reply.status(201).send(present({ _id: insertedId, ...doc }));',
    '  });',
    '',
    "  app.patch('/:id', { schema: { params, body: updateBody } }, async (req) => {",
    '    const doc = await collection.findOneAndUpdate(',
    '      { _id: new ObjectId(req.params.id) },',
    '      { $set: { ...req.body, updatedAt: new Date() } },',
    "      { returnDocument: 'after' }",
    '    );',
    `    if (!doc) throw notFound('${res.name} item not found');`,
    '    return present(doc);',
    '  });',
    '',
    "  app.delete('/:id', { schema: { params } }, async (req, reply) => {",
    '    const { deletedCount } = await collection.deleteOne({ _id: new ObjectId(req.params.id) });',
    `    if (!deletedCount) throw notFound('${res.name} item not found');`,
    '    return reply.status(204).send();',
    '  });',
    '}',
    ''
  ].join('\n');
}

/** Next migration number given the paths already in the repo. */
export function nextMigrationNumber(paths) {
  let max = 0;
  for (const p of paths) {
    const m = /^migrations\/(\d{4})_/.exec(p);
    if (m) max = Math.max(max, Number(m[1]));
  }
  return String(max + 1).padStart(4, '0');
}

export function buildResource(spec, db, paths) {
  const res = validateResource(spec, db);
  const files = [{ path: `src/routes/${res.name}.js`, content: db === 'postgres' ? postgresRoutes(res) : mongoRoutes(res) }];
  if (db === 'postgres') files.push({ path: `migrations/${nextMigrationNumber(paths)}_create_${res.name}.sql`, content: migrationSql(res) });
  return { res, files };
}
