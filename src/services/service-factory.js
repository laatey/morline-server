import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { DATA_DIR } from '../config.js';
import { execute, queryOne, transaction } from '../db/index.js';
import { mapService } from '../db/mappers.js';
import { eventBus } from '../engine/event-bus.js';
import { buildManager } from '../engine/build-manager.js';

const rid = (prefix) => `${prefix}_${crypto.randomUUID().replace(/-/g, '').slice(0, 16)}`;

/**
 * Create a service that builds from a GitHub repo, or (repo = null) from files written straight
 * into its build workspace. Returns the service row.
 */
export function createRepoService({ environmentId, name, repo, branch, port = 3000, variables = [], volume = null }) {
  const env = queryOne('SELECT * FROM environments WHERE id = ?', environmentId);
  if (!env) throw new Error('The environment for this app no longer exists');

  let serviceName = name;
  for (let i = 2; queryOne('SELECT 1 AS x FROM services WHERE environment_id = ? AND name = ?', environmentId, serviceName); i++) {
    serviceName = `${name}-${i}`;
  }
  const count = queryOne('SELECT COUNT(*) AS c FROM services WHERE environment_id = ?', environmentId)?.c || 0;
  const serviceId = rid('srv');
  const now = new Date().toISOString();

  transaction(() => {
    execute(`
      INSERT INTO services (id, environment_id, name, kind, logo, status, position_x, position_y, source_type, source_repo, source_branch, source_display, region, replicas, created_at, updated_at)
      VALUES (?, ?, ?, 'app', 'js', 'created', ?, ?, ?, ?, ?, ?, 'us-east-1', 1, ?, ?)
    `, serviceId, environmentId, serviceName, 100 + (count % 4) * 280, 100 + Math.floor(count / 4) * 200,
      repo ? 'github' : 'local', repo || null, repo ? branch : null, repo || 'Generated by Morline AI', now, now);
    execute(`
      INSERT INTO service_settings (service_id, branch, auto_deploy, healthcheck_path, healthcheck_timeout_sec, restart_policy, replicas)
      VALUES (?, ?, ?, '/health', 30, 'on-failure', 1)
    `, serviceId, repo ? branch : null, repo ? 1 : 0);
    execute('INSERT INTO service_networking (service_id, public, target_port) VALUES (?, 1, ?)', serviceId, port);
    if (volume) {
      const volId = rid('vol');
      execute(`
        INSERT INTO volumes (id, service_id, name, mount_path, size_gb, used_gb, created_at)
        VALUES (?, ?, 'data', ?, ?, 0.0, ?)
      `, volId, serviceId, volume.mountPath, volume.sizeGb, now);
      try { fs.mkdirSync(path.join(DATA_DIR, 'service-volumes', serviceId, volId), { recursive: true }); } catch { /* created on first start */ }
    }
    for (const v of variables) {
      execute(`
        INSERT INTO variables (id, scope_type, scope_id, key, value, secret, created_at, updated_at)
        VALUES (?, 'service', ?, ?, ?, ?, ?, ?)
      `, rid('var'), serviceId, v.key, v.value, v.secret ? 1 : 0, now, now);
    }
  });

  const row = queryOne('SELECT * FROM services WHERE id = ?', serviceId);
  eventBus.emitEnvironmentEvent(environmentId, {
    type: 'service.created', at: now, actorId: null, canvasRevision: env.canvas_revision, data: mapService(row)
  });
  return row;
}

/** Queue and start a deployment. Returns the deployment id. */
export function startDeployment({ serviceId, userId = null, commitSha = null, message = null, branch = null }) {
  const service = queryOne('SELECT * FROM services WHERE id = ?', serviceId);
  if (!service) throw new Error('Service not found');
  const id = rid('dep');
  execute(`
    INSERT INTO deployments (id, service_id, service_name, environment_id, state, trigger, commit_sha, commit_message, commit_branch, created_by, created_at)
    VALUES (?, ?, ?, ?, 'queued', 'assistant', ?, ?, ?, ?, ?)
  `, id, serviceId, service.name, service.environment_id, commitSha, message, branch, userId, new Date().toISOString());
  buildManager.buildAndDeploy(serviceId, id).catch((err) => console.error('[Assistant deploy]', err.message));
  return id;
}

/** Write generated files into a service's build workspace (the no-GitHub path). */
export function writeWorkspaceFiles(serviceId, files) {
  const dir = path.resolve(buildManager.getWorkspaceDir(serviceId));
  for (const f of files) {
    const target = path.resolve(dir, f.path);
    if (!target.startsWith(dir + path.sep)) throw new Error(`Refusing to write outside the workspace: ${f.path}`);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, f.content, 'utf8');
  }
}

const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'build', '.next', '__pycache__', '.venv', 'target']);

/** Every readable file in a service's build workspace, as `{ path, sha, size }` (sha is unused locally). */
export function listWorkspaceFiles(serviceId) {
  const root = path.resolve(buildManager.getWorkspaceDir(serviceId));
  const out = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) walk(path.join(dir, entry.name));
      } else if (entry.isFile()) {
        const abs = path.join(dir, entry.name);
        out.push({ path: path.relative(root, abs).split(path.sep).join('/'), sha: null, size: fs.statSync(abs).size });
      }
    }
  };
  walk(root);
  return out;
}

/** File text from the workspace, or null when it is missing or binary. */
export function readWorkspaceFile(serviceId, rel) {
  const root = path.resolve(buildManager.getWorkspaceDir(serviceId));
  const abs = path.resolve(root, rel);
  if (!abs.startsWith(root + path.sep) || !fs.existsSync(abs)) return null;
  const buf = fs.readFileSync(abs);
  return buf.includes(0) ? null : buf.toString('utf8');
}

/** Apply `[{ path, action, content }]` to the workspace. */
export function applyWorkspaceChanges(serviceId, changes) {
  const root = path.resolve(buildManager.getWorkspaceDir(serviceId));
  for (const c of changes) {
    const abs = path.resolve(root, c.path);
    if (!abs.startsWith(root + path.sep)) throw new Error(`Refusing to write outside the workspace: ${c.path}`);
    if (c.action === 'delete') { fs.rmSync(abs, { force: true }); continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, c.content, 'utf8');
  }
}
